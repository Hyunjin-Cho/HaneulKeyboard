#!/usr/bin/env python3
"""2026-11-07 (#175): 번들 사전 표(Resources/IM/english_bundled.txt)를 만들고 검사한다.

입력기는 이 파일을 매핑해 이진 탐색한다(IMESources/KoreanDictionary.swift의 SortedWordTable).
입력은 dict_work/dict_manifest.tsv에 적힌 번들 사전뿐이다. web2(/usr/share/dict/words)는 넣지 않는다.
입력기는 web2를 시스템 파일 그대로 매핑해 찾는다(IMESources/EnglishDetector.swift의 SystemWordFile).
2026-11-07 오너 결정: 저장소와 앱에 web2 낱말이 들어가면 안 된다.

사용:
  scripts/build_english_table.py          # 표를 다시 쓴다 (사전을 고친 뒤 실행)
  scripts/build_english_table.py --check  # 표가 번들 사전 합집합과 어긋나면 실패 (쓰지 않음)

필터는 EnglishDetector.isWordLine과 같다: 첫 글자가 a-z, 3자 이상, ASCII 알파벳만, 소문자화.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "dict_work/dict_manifest.tsv"
TABLE = ROOT / "Resources/IM/english_bundled.txt"
LINE = re.compile(rb"[a-z][A-Za-z]{2,}")

TABLE_HEADER = """\
# HaneulKeyboard bundled English table. GENERATED by scripts/build_english_table.py. Do not edit.
# Inputs: only the bundled lists named in dict_work/dict_manifest.tsv.
# Web2 (/usr/share/dict/words) is NOT included. The IME reads that macOS system file in place.
# Format: UTF-8 byte order, LF only, one word per line. The IME maps this file and binary-searches it.
# Sources: NGSL (CC BY-SA 4.0); SCOWL/ESDB (MIT-like); US Census and SSA names (public domain);
#   GeoNames (CC BY 4.0); Wikidata (CC0); lists curated by this project. Attribution: ACKNOWLEDGEMENTS.md.
"""


def die(message):
    sys.exit(f"오류: {message}")


def loader_words(path):
    """EnglishDetector.isWordLine과 같은 필터로 파일의 낱말을 읽는다."""
    words = set()
    for raw in path.read_bytes().split(b"\n"):
        if LINE.fullmatch(raw):
            words.add(raw.decode("ascii").lower())
    return words


def manifest_names():
    names = []
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            names.append(line.split("\t")[0].strip())
    if not names:
        die(f"manifest가 비었다: {MANIFEST}")
    return names


def bundled_words():
    words = set()
    for name in manifest_names():
        path = ROOT / f"Resources/IM/{name}.txt"
        if not path.exists():
            die(f"manifest에 적힌 사전이 없다: {path}")
        words |= loader_words(path)
    return words


def table_bytes(words):
    ordered = sorted(words)  # 전부 ASCII 소문자라 코드 포인트 순 = UTF-8 바이트 순
    body = "".join(word + "\n" for word in ordered)
    # `# count:` 줄은 SortedWordTable이 읽어 낱말 수와 대조한다. 머리글의 다른 줄에 이 표기를 쓰지 않는다.
    return (TABLE_HEADER + f"# count: {len(ordered)}\n" + body).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="표가 번들 사전 합집합과 다르면 실패한다. 파일을 쓰지 않는다")
    args = parser.parse_args()
    words = bundled_words()
    expected = table_bytes(words)
    if args.check:
        current = TABLE.read_bytes() if TABLE.exists() else b""
        if current != expected:
            lines = {raw.decode("ascii", "replace") for raw in current.split(b"\n") if raw and not raw.startswith(b"#")}
            foreign = sorted(lines - words)[:5]
            die(f"{TABLE}가 번들 사전과 어긋난다(번들 사전에 없는 낱말 예: {foreign}). scripts/build_english_table.py 를 실행해 다시 만든다.")
        print(f"표 일치: {TABLE.name}")
        return
    TABLE.write_bytes(expected)
    print(f"{TABLE}: {len(words):,}단어, {len(expected):,}바이트")


if __name__ == "__main__":
    main()
